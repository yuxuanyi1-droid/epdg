// renderEnv writes deploy/.env, which is how docker-compose learns the static
// addresses, ports and credentials.
func (r *Renderer) renderEnv() error {
	lab := r.Lab
	var b strings.Builder
	b.WriteString("# Generated by `labctl render` from deploy/lab.yaml. Do not edit.\n")
	b.WriteString("# docker-compose reads this file for the bridge addresses and ports.\n\n")
	fmt.Fprintf(&b, "LAB_SUBNET=%s\n", lab.Network.Subnet)
	b.WriteString("LAB_HOST_ADDRESS=" + lab.Network.HostAddress + "\n")
	for _, node := range sortedKeys(lab.Network.Nodes) {
		fmt.Fprintf(&b, "IP_%s=%s\n", strings.ToUpper(node), lab.Network.Nodes[node])
	}
	fmt.Fprintf(&b, "\nPLMN_MCC=%s\nPLMN_MNC=%s\nPLMN_MNC3=%s\nPLMN_REALM=%s\n",
		lab.PLMN.MCC, lab.PLMN.MNC, lab.PLMN.MNC3, lab.PLMN.Realm())
	fmt.Fprintf(&b, "\nKAMAILIO_DB_PASSWORD=%s\nRADIUS_SECRET=%s\n",
		lab.Credentials.KamailioDBPassword, lab.Credentials.RadiusSecret)
	fmt.Fprintf(&b, "IMSI=%s\nKI=%s\nOPC=%s\n",
		lab.Credentials.IMSI, lab.Credentials.KI, lab.Credentials.OPC)
	fmt.Fprintf(&b, "\nEPDG_HTTP_PORT=%d\nEPDG_RADIUS_PORT=%d\nEPDG_IKE_PORT=%d\nEPDG_NATT_PORT=%d\n",
		portOf(lab.EPDG.HTTP.Listen, 19090), portOf(lab.EPDG.RADIUS.Listen, 18120),
		orDefault(lab.EPDG.Protocol.SWu.IKEPort, 500), orDefault(lab.EPDG.Protocol.SWu.NATTPort, 4500))
	fmt.Fprintf(&b, "OPEN5GS_GTPC_PORT=%d\nOPEN5GS_PFCP_PORT=%d\n",
		orDefault(lab.Open5GS.GTPCPort, 2123), orDefault(lab.Open5GS.PFCPPort, 8805))
	fmt.Fprintf(&b, "\n# Profiles drive which optional services docker-compose starts.\n")
	fmt.Fprintf(&b, "COMPOSE_PROFILES=%s\n", strings.Join(r.profiles(), ","))

	path := filepath.Join(r.DeployDir, ".env")
	if err := os.WriteFile(path, []byte(b.String()), 0o644); err != nil {
		return fmt.Errorf("render: cannot write %s: %w", path, err)
	}
	return nil
}

// profiles decides which compose profiles are active from the lab definition.
func (r *Renderer) profiles() []string {
	profiles := []string{"core"}
	if r.Lab.Open5GS.Enabled {
		profiles = append(profiles, "epc")
	}
	if r.Lab.Open5GS.Enabled && r.Lab.Open5GS.HSSBackend == "open5gs" {
		profiles = append(profiles, "open5gs-hss")
	}
	if r.Lab.ENB.Enabled {
		profiles = append(profiles, "enb")
	}
	return profiles
}

