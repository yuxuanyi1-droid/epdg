// kamailioRole describes one CSCF for the address rewrite below.
type kamailioRole struct {
	name     string
	self     string
	ports    []string
	acceptor string
}

// renderKamailio rewrites the three CSCF configurations onto the container
// addresses. The shipped configs are kept as they are; only addresses and paths
// change.
func (r *Renderer) renderKamailio() error {
	lab := r.Lab
	mariadb := lab.Network.Node("mariadb")
	dbPassword := lab.Credentials.KamailioDBPassword
	icscf := lab.Network.Node("icscf")
	scscf := lab.Network.Node("scscf")

	roles := []kamailioRole{
		{name: "pcscf", self: lab.Network.Node("pcscf"), ports: []string{"5060"},
			acceptor: `<Acceptor port="3871" bind="11.22.33.44"/>`},
		{name: "icscf", self: icscf, ports: []string{"5061", "4060"},
			acceptor: `<Acceptor port="3869" bind="127.0.0.1"/>`},
		{name: "scscf", self: scscf, ports: []string{"5062", "6060"},
			acceptor: `<Acceptor port="3870" bind="127.0.0.1"/>`},
	}

	for _, role := range roles {
		subs := [][2]string{
			// Database. The shipped configs point at a local mysqld.
			{fmt.Sprintf("mysql://%s:heslo@127.0.0.1/%s", role.name, role.name),
				fmt.Sprintf("mysql://%s:%s@%s/%s", role.name, dbPassword, mariadb, role.name)},
			// Inter-CSCF routing: the P-CSCF needs the I-CSCF, the I-CSCF the S-CSCF.
			// These come first so a node's own port substitutions below cannot
			// capture another node's address.
			{`sip:127.0.0.1:5061`, fmt.Sprintf("sip:%s:5061", icscf)},
			{`$rd = "127.0.0.1:5062";`, fmt.Sprintf(`$rd = "%s:5062";`, scscf)},
			{`1 sip:127.0.0.1:5062`, fmt.Sprintf("1 sip:%s:5062", scscf)},
			// Listen sockets. The 10.x addresses were the tunnel and IPsec
			// sockets of the single host lab; drop them entirely rather than
			// remapping, otherwise the socket is declared twice on the same
			// address and kamailio rejects the config.
			{"listen=udp:10.255.0.1:5060\n", ""},
			{"listen=udp:10.46.0.1:5060\n", ""},
			// Control and config paths move onto the container layout.
			{`/etc/kamailio_` + role.name, `/etc/kamailio`},
			{`/run/kamailio_` + role.name, `/run/kamailio`},
			// These two are host tuning: they try to pre-fault and wire the whole
			// shared memory pool. In a container the mlock fails, and the
			// registrar save path then dies with SIGSEGV, so leave the pool to
			// grow on demand.
			{`mlock_pages=yes`, `mlock_pages=no`},
			{`shm_force_alloc=yes`, `shm_force_alloc=no`},
			// The P-CSCF advertises itself to the I-CSCF; it must be routable.
			{`#!define PCSCF_URL "sip:pcscf.localdomain"`,
				fmt.Sprintf(`#!define PCSCF_URL "sip:%s:5060"`, lab.Network.Node("pcscf"))},
		}
		for _, port := range role.ports {
			subs = append(subs,
				[2]string{`listen=udp:127.0.0.1:` + port, fmt.Sprintf("listen=udp:%s:%s", role.self, port)},
				[2]string{`listen=tcp:127.0.0.1:` + port, fmt.Sprintf("listen=tcp:%s:%s", role.self, port)},
			)
		}
		// The node's own SIP URI must name the address its peers can reach.
		// `#!define URI "sip:127.0.0.1:5062"` feeds ims_auth's name and the
		// registrar's scscf_name, which go into the Path header and the SAR. If
		// it keeps pointing at 127.0.0.1 while the node listens on its container
		// address, the registrar dereferences a lookup that cannot match and the
		// S-CSCF dies on the first registration. Applied last so it only catches
		// whatever the inter-node rules above did not already claim.
		for _, port := range role.ports {
			subs = append(subs, [2]string{"127.0.0.1:" + port, role.self + ":" + port})
		}
		// The Diameter acceptor binds the node address.
		subs = append(subs, [2]string{role.acceptor,
			strings.Replace(strings.Replace(role.acceptor, "11.22.33.44", role.self, 1),
				"127.0.0.1", role.self, 1)})

		if err := r.copyTree("configs/kamailio/"+role.name, "kamailio/"+role.name, subs); err != nil {
			return err
		}
	}
	return nil
}

// renderOpen5GS rewrites the EPC configurations and generates the freeDiameter
// peer files the MME and the SMF need in order to reach the HSS.
func (r *Renderer) renderOpen5GS() error {
	if !r.Lab.Open5GS.Enabled {
		return nil
	}
	lab := r.Lab

	// The shipped configs are addressed to the 127.0.0.x layout of the single
	// host lab. Map each of those onto the container that now owns the role.
	legacy := [][2]string{
		{"127.0.0.2", lab.Network.Node("mme")},
		{"127.0.0.3", lab.Network.Node("sgwc")},
		{"127.0.0.4", lab.Network.Node("smf")},
		{"127.0.0.6", lab.Network.Node("sgwu")},
		{"127.0.0.7", lab.Network.Node("upf")},
	}
	if mongo := lab.Network.Node("mongo"); mongo != "" {
		legacy = append(legacy, [2]string{"mongodb://localhost/open5gs",
			fmt.Sprintf("mongodb://%s/open5gs", mongo)})
	}
	if lab.Open5GS.HSSBackend == "open5gs" {
		legacy = append(legacy,
			[2]string{"127.0.0.8", lab.Network.Node("o5gshss")},
			[2]string{"127.0.0.9", lab.Network.Node("o5gpcrf")})
	} else {
		// PyHSS answers both the S6a and the Gx reference points.
		legacy = append(legacy,
			[2]string{"127.0.0.8", lab.Network.Node("pyhss")},
			[2]string{"127.0.0.9", lab.Network.Node("pyhss")})
	}

	// Copy the shipped configs first: not every file mentions every address, so
	// the substitution list is applied per file and non-matches are ignored.
	if err := r.copyTree("configs/open5gs", "open5gs", legacy); err != nil {
		return err
	}
	// The shipped configs also carry parameter values (MME identity, PLMN, the
	// SGW-U address). Those come from lab.yaml, so rewrite them too: the UI edits
	// them and a render has to make the edit real.
	if err := r.applyOpen5GSParameters(); err != nil {
		return err
	}
	// The repository does not ship an SMF/PGW or a UPF config; generate them.
	for _, name := range []string{"smf", "upf"} {
		if _, err := os.Stat(filepath.Join(r.RuntimeDir, "open5gs", name+".yaml")); err == nil {
			continue
		}
		if err := r.write("open5gs/"+name+".yaml", generatedOpen5GSYAML(name), lab); err != nil {
			return err
		}
	}

	// freeDiameter carries S6a from the MME and Gx/S6b from the SMF.
	//
	// The MME only needs S6a, which PyHSS answers. The SMF needs Gx *and* S6b,
	// and an S2b (WLAN) session is refused outright unless both have an
	// answering peer: PyHSS implements Cx, Sh, Rx, Gx and S6a but not S6b, so
	// the SMF is pointed at the Gx/S6b test peer instead.
	hssName, hssAddr := "hss.localdomain", lab.Network.Node("pyhss")
	if lab.Open5GS.HSSBackend == "open5gs" {
		hssAddr = lab.Network.Node("o5gshss")
	}
	smfName, smfAddr := hssName, hssAddr
	if aaa := lab.Network.Node("aaa"); aaa != "" {
		smfName, smfAddr = "aaa.localdomain", aaa
	}
	for _, p := range []struct{ name, identity, listen, peerName, peerAddr string }{
		{"mme.conf", "mme.localdomain", lab.Network.Node("mme"), hssName, hssAddr},
		{"smf.conf", "smf.localdomain", lab.Network.Node("smf"), smfName, smfAddr},
	} {
		if err := r.write("freediameter/"+p.name,
			freeDiameterConf(p.identity, p.listen, p.peerName, p.peerAddr), nil); err != nil {
			return err
		}
	}
	if lab.Open5GS.HSSBackend == "open5gs" {
		for _, p := range []struct{ name, identity, listen string }{
			{"hss.conf", "hss.localdomain", lab.Network.Node("o5gshss")},
			{"pcrf.conf", "pcrf.localdomain", lab.Network.Node("o5gpcrf")},
		} {
			if err := r.write("freediameter/"+p.name,
				freeDiameterConf(p.identity, p.listen, "smf.localdomain", lab.Network.Node("smf")), nil); err != nil {
				return err
			}
		}
	}
	return nil
}

// applyOpen5GSParameters rewrites the parameter values the UI exposes. The
// left hand side of each pair is the value shipped in configs/open5gs, so a
// change there is caught rather than silently ignored.
func (r *Renderer) applyOpen5GSParameters() error {
	lab := r.Lab
	mme := lab.Open5GS.MME

	mmeSubs := [][2]string{
		{"mme_name: open5gs-mme0", "mme_name: " + mme.MMEName},
		{"mme_gid: 2", fmt.Sprintf("mme_gid: %d", mme.MMEGID)},
		{"mme_code: 1", fmt.Sprintf("mme_code: %d", mme.MMECode)},
		{"      tac: 1", fmt.Sprintf("      tac: %d", mme.TAC)},
		{"    full: Open5GS", "    full: " + mme.NetworkNameFull},
		{"    short: Next", "    short: " + mme.NetworkNameShort},
		{"integrity_order : [ EIA2, EIA1, EIA0 ]",
			fmt.Sprintf("integrity_order : [ %s ]", strings.Join(mme.IntegrityOrder, ", "))},
		{"ciphering_order : [ EEA0, EEA1, EEA2 ]",
			fmt.Sprintf("ciphering_order : [ %s ]", strings.Join(mme.CipheringOrder, ", "))},
		// The PLMN appears twice: GUMMEI and TAI.
		{"        mcc: 001", "        mcc: " + lab.PLMN.MCC},
		{"        mnc: 01", "        mnc: " + lab.PLMN.MNC},
	}
	if err := r.substituteInRuntime("open5gs/mme.yaml", mmeSubs); err != nil {
		return err
	}

	// The SGW-U advertises its GTP-U endpoint to the eNB; the address comes from
	// lab.yaml rather than from the legacy 127.0.0.x mapping.
	sgwuSubs := [][2]string{
		{"      - address: " + lab.Network.Node("sgwu"),
			"      - address: " + lab.Open5GS.SGW.GTPUAddress},
	}
	if err := r.substituteInRuntime("open5gs/sgwu.yaml", sgwuSubs); err != nil {
		return err
	}
	return nil
}

// substituteInRuntime rewrites a file that is already in the runtime tree.
func (r *Renderer) substituteInRuntime(dstRel string, subs [][2]string) error {
	path := filepath.Join(r.RuntimeDir, dstRel)
	body, err := os.ReadFile(path)
	if err != nil {
		return fmt.Errorf("render: cannot read %s: %w", path, err)
	}
	text := string(body)
	for _, sub := range subs {
		if !strings.Contains(text, sub[0]) {
			return fmt.Errorf("render: %s does not contain %q, the shipped config changed", dstRel, sub[0])
		}
		text = strings.ReplaceAll(text, sub[0], sub[1])
	}
	if err := os.WriteFile(path, []byte(text), 0o644); err != nil {
		return fmt.Errorf("render: cannot write %s: %w", path, err)
	}
	return nil
}

// freeDiameterConf renders a freeDiameter peer that talks to one peer over TCP.
// TLS material is required by freeDiameter even for plain TCP peers, so the
// image generates a self-signed certificate at /etc/open5gs/tls.
//
// peerName must equal the peer's own Origin-Host. freeDiameter rejects a CEA
// whose Origin-Host does not match the identity the peer was configured with,
// and the failure is reported as "save_remote_CE_info: Invalid argument" with
// the peer never reaching OPEN, which looks like an encoding bug in the peer.
